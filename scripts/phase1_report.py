"""Phase 1 report: every test magnet x noise level x regulariser, graded against the pass bar.

Run:  .venv/bin/python scripts/phase1_report.py  [--seeds 3]
Writes docs/phase1-results.md.
"""

from __future__ import annotations

import argparse
import pathlib
import statistics as st

import numpy as np

from app.sim import magnets
from app.sim.phone import NOISE
from app.sim.session import run_session

BAR = {"field_err": 0.10, "moment_err": 0.15, "piece_cos": 0.7, "coverage": 0.80, "seconds": 1.0}
GRADED = ("ring", "bar", "disc", "broken")


def passes(name, s):
    ok = s.field_err <= BAR["field_err"] and s.unc_coverage >= BAR["coverage"]
    ok &= s.fit_seconds <= BAR["seconds"]
    if name == "broken":
        ok &= min(s.piece_cos) >= BAR["piece_cos"]
    elif name != "two":
        ok &= s.moment_err <= BAR["moment_err"]
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--methods", default="tikhonov,sparse")
    ap.add_argument("--noise", default="ideal,realistic,poor")
    ap.add_argument(
        "--no-table", action="store_true", help="do not tell the solver the table plane"
    )
    args = ap.parse_args()
    rows = []
    for method in args.methods.split(","):
        for noise in args.noise.split(","):
            for name in magnets.ALL:
                runs = [
                    run_session(
                        magnets.ALL[name](),
                        NOISE[noise],
                        noise,
                        method=method,
                        seed=k,
                        use_table=not args.no_table,
                    )
                    for k in range(args.seeds)
                ]
                first = [r.history[0] for r in runs]
                last = [r.history[-1] for r in runs]
                n_pass = sum(passes(name, s) for s in last)
                rows.append(
                    {
                        "method": method,
                        "noise": noise,
                        "magnet": name,
                        "h_mm": runs[0].scan_height * 1e3,
                        "voxel_mm": runs[0].fit.grid.size * 1e3,
                        "fe0": st.median(s.field_err for s in first),
                        "fe": st.median(s.field_err for s in last),
                        "me": st.median(s.moment_err for s in last)
                        if name != "two"
                        else float("nan"),
                        "cos": st.median(min(s.piece_cos) for s in last),
                        "cov": st.median(s.unc_coverage for s in last),
                        "unc": st.median(s.rel_unc for s in last),
                        "hole": st.median(s.hole_ratio for s in last),
                        "sec": max(s.fit_seconds for s in last),
                        "pass": f"{n_pass}/{len(runs)}",
                    }
                )
                r = rows[-1]
                print(
                    f"{method:8s} {noise:9s} {name:6s} "
                    f"h={r['h_mm']:.0f}mm vox={r['voxel_mm']:.0f}mm "
                    f"field {r['fe0']:.3f}->{r['fe']:.3f} moment {r['me']:.3f} cos {r['cos']:.2f} "
                    f"cov {r['cov']:.2f} unc {r['unc']:.3f} hole {r['hole']:.2f} "
                    f"{r['sec']:.2f}s pass {r['pass']}",
                    flush=True,
                )
    write_markdown(rows, args.seeds)


def write_markdown(rows, seeds):
    out = [
        "# Phase 1 results",
        "",
        "Generated by `scripts/phase1_report.py`. Medians over "
        f"{seeds} random seeds per row; *pass* counts seeds meeting the bar in "
        "`phase1-pass-bar.md` after the guided swipes.",
        "",
        "Columns: scan height chosen to stay under 70 % of the sensor range; voxel edge; field "
        "error after the 6 starting swipes → after up to 4 guided swipes; total-moment error; "
        "lowest per-piece direction cosine; share of errors inside the 2σ band; reported relative "
        "uncertainty; ring-hole ratio (|M| in the hole ÷ |M| in the ring, < 1 means a hole is "
        "seen); slowest fit.",
        "",
        "| Regulariser | Noise | Magnet | Height mm | Voxel mm | Field err (6 → 10 swipes) | "
        "Moment err | Piece cos | 2σ coverage | Reported unc | Hole ratio | Fit s | Pass |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        out.append(
            f"| {r['method']} | {r['noise']} | {r['magnet']} | {r['h_mm']:.0f} | "
            f"{r['voxel_mm']:.0f} | {r['fe0']:.1%} → {r['fe']:.1%} | {r['me']:.1%} | "
            f"{r['cos']:.2f} | {r['cov']:.0%} | {r['unc']:.1%} | {r['hole']:.2f} | "
            f"{r['sec']:.2f} | {r['pass']} |"
        )
    path = pathlib.Path(__file__).resolve().parents[1] / "docs" / "phase1-results.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
